/* Generate css/fonts.css — Computer Modern, embedded as base64 so the
   single-file build needs no network and no installed fonts.
   Faces come from KaTeX (MIT, see fonts/LICENSE-KaTeX.txt); they are
   Computer Modern derivatives, the same design LaTeX's article class uses.

   Run:  node tools/genfonts.js */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'fonts');

/* Big operators and the double-bar exist only in the Size faces — cmex in
   TeX terms. Everything else comes from Main / Math / AMS. */
const BIG_OPS = 'U+2016, U+220F-2211, U+222B-222E, U+22C0-22C3, U+2A00-2A02';

const FACES = [
  { file: 'KaTeX_Main-Regular',      family: 'PaperTeX',       weight: 400, style: 'normal' },
  { file: 'KaTeX_Main-Bold',         family: 'PaperTeX',       weight: 700, style: 'normal' },
  { file: 'KaTeX_Main-Italic',       family: 'PaperTeX',       weight: 400, style: 'italic' },
  { file: 'KaTeX_Size1-Regular',     family: 'PaperTeX',       weight: 400, style: 'normal', range: BIG_OPS },
  { file: 'KaTeX_Math-Italic',       family: 'PaperTeX Math',  weight: 400, style: 'italic' },
  { file: 'KaTeX_Math-Italic',       family: 'PaperTeX Math',  weight: 400, style: 'normal' },
  { file: 'KaTeX_AMS-Regular',       family: 'PaperTeX AMS',   weight: 400, style: 'normal' },
  { file: 'KaTeX_Caligraphic-Regular', family: 'PaperTeX Cal', weight: 400, style: 'normal' },
  /* the \big and \Big sizes of delimiters and radicals */
  { file: 'KaTeX_Size1-Regular',     family: 'PaperTeX Size1', weight: 400, style: 'normal' },
  { file: 'KaTeX_Size2-Regular',     family: 'PaperTeX Size2', weight: 400, style: 'normal' }
];

/* KaTeX's faces stop at English: no ç ğ ş ö ü é, no Greek in the text
   face, few dashes and quotes. Those come from CMU Serif (Computer Modern
   Unicode, SIL OFL — see fonts/LICENSE-CMU.txt), the same design, cut down
   to exactly the characters KaTeX lacks; the ranges in
   fonts/CMU-ranges.json say which, so a glyph KaTeX draws is never
   replaced. tools/subset-cmu.py makes the cut and the ranges. */
const CMU = JSON.parse(fs.readFileSync(path.join(dir, 'CMU-ranges.json'), 'utf8'));
[['CMU-Serif-Regular-ext', 400, 'normal'], ['CMU-Serif-Bold-ext', 700, 'normal'], ['CMU-Serif-Italic-ext', 400, 'italic']]
  .forEach(([file, weight, style]) => {
    FACES.push({ file, family: 'PaperTeX', weight, style, range: CMU[file + '.woff2'] });
  });

let css = `/* PaperTeX — embedded Computer Modern.
   Generated by tools/genfonts.js; do not edit by hand.
   Faces derived from KaTeX (MIT) — see fonts/LICENSE-KaTeX.txt — and, for
   the letters beyond English, CMU Serif (SIL OFL) — see fonts/LICENSE-CMU.txt.
   Computer Modern is the typeface LaTeX's article class sets by default,
   so the page on screen matches what the exported .tex will compile to. */\n\n`;

let total = 0;
for (const f of FACES) {
  const buf = fs.readFileSync(path.join(dir, f.file + '.woff2'));
  total += buf.length;
  css += `@font-face {\n` +
    `  font-family: "${f.family}";\n` +
    `  font-style: ${f.style};\n` +
    `  font-weight: ${f.weight};\n` +
    `  font-display: block;\n` +
    (f.range ? `  unicode-range: ${f.range};\n` : '') +
    `  src: url(data:font/woff2;base64,${buf.toString('base64')}) format("woff2");\n` +
    `}\n\n`;
}

fs.writeFileSync(path.join(root, 'css', 'fonts.css'), css);
console.log(`css/fonts.css  ${FACES.length} faces, ${(total / 1024).toFixed(0)} kB raw ` +
            `-> ${(fs.statSync(path.join(root, 'css', 'fonts.css')).size / 1024).toFixed(0)} kB base64`);
